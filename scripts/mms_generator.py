#!/usr/bin/env python3
r"""
Method of Manufactured Solutions (MMS) Generator for PDE/ODE Verification.

Uses SymPy to analytically substitute a manufactured exact solution into a
differential operator, deriving the exact analytical source term f(x, t)
and writing a module with exact_solution and source_term. check_against_reference.py convergence-user
then measures the observed order of the user's solver against it.

Usage:
    python3 scripts/mms_generator.py --exact "sin(pi*x) * exp(-t)" \
                                     --operator "diff(u, t) - alpha * diff(u, x, 2)" \
                                     --params "alpha=0.1" \
                                     --output mms_heat.py

The coordinates of the generated functions are those of x, y, z, t the expressions use, in that order, or the
ones given with --vars "x,y,t".
"""

import sys
import argparse
import sympy as sp


def generate_mms(exact_expr_str: str, operator_expr_str: str, params_str: str = "", output_file: str = "",
                 vars_str: str = ""):
    # Symbols
    t, x, y, z = sp.symbols('t x y z', real=True)
    pi = sp.pi

    # Parse parameter dict
    param_dict = {}
    if params_str:
        for p in params_str.split(","):
            if "=" in p:
                k, v = p.split("=")
                k = k.strip()
                v = float(v.strip())
                param_dict[sp.Symbol(k, real=True)] = v

    # Local evaluation environment
    local_env = {
        't': t, 'x': x, 'y': y, 'z': z,
        'pi': pi, 'sin': sp.sin, 'cos': sp.cos,
        'exp': sp.exp, 'log': sp.log, 'sqrt': sp.sqrt,
    }
    for k in param_dict:
        local_env[str(k)] = k

    # Parse exact manufactured solution u_exact
    u_exact = sp.sympify(exact_expr_str, locals=local_env)

    # Function u(t, x, y, z) for operator evaluation
    # Substitute u with u_exact in operator
    local_env_op = dict(local_env)
    local_env_op['u'] = u_exact
    local_env_op['diff'] = sp.diff

    # Evaluate forcing term f = Operator[u_exact]
    forcing_term = sp.sympify(operator_expr_str, locals=local_env_op)
    forcing_term_simplified = sp.simplify(forcing_term)

    # Substitute numerical parameter values
    forcing_numerical = forcing_term_simplified.subs(param_dict)
    u_exact_numerical = u_exact.subs(param_dict)

    # The arguments of the generated functions, in a stated order
    named = {'x': x, 'y': y, 'z': z, 't': t}
    if vars_str:
        names = [name.strip() for name in vars_str.split(",") if name.strip()]
        unknown = [name for name in names if name not in named]
        if unknown:
            raise SystemExit(f"mms_generator: --vars may name x, y, z and t only, got {unknown}")
        coordinates = [named[name] for name in names]
    else:
        used = u_exact_numerical.free_symbols | forcing_numerical.free_symbols
        coordinates = [symbol for symbol in (x, y, z, t) if symbol in used] or [x]
    leftover = (u_exact_numerical.free_symbols | forcing_numerical.free_symbols) - set(coordinates)
    if leftover:
        raise SystemExit(f"mms_generator: no value or coordinate for {sorted(map(str, leftover))}: give it in --params or --vars")

    # Generate LaTeX representations
    latex_exact = sp.latex(u_exact)
    latex_forcing = sp.latex(forcing_term_simplified)

    print("=" * 70)
    print("Method of Manufactured Solutions (MMS) Symbolic Derivation:")
    print("=" * 70)
    print(f"Manufactured Solution u_exact(x, t):\n  LaTeX: {latex_exact}\n  SymPy: {u_exact}\n")
    print(f"Differential Operator:\n  L[u] = {operator_expr_str}\n")
    print(f"Exact Analytical Forcing Term f = L[u_exact]:\n  LaTeX: {latex_forcing}\n  SymPy: {forcing_term_simplified}\n")
    if param_dict:
        print(f"Numerical Forcing Term (with params {params_str}):\n  SymPy: {forcing_numerical}\n")
    print("=" * 70)

    # Generate Python code
    py_code_u = sp.pycode(u_exact_numerical)
    py_code_f = sp.pycode(forcing_numerical)

    print("Python Implementations:")
    arguments = ", ".join(str(symbol) for symbol in coordinates)
    print(f"def exact_solution({arguments}):\n    return {py_code_u}\n")
    print(f"def source_term({arguments}):\n    return {py_code_f}\n")

    if output_file:
        signature = ", ".join(str(symbol) for symbol in coordinates)
        command = (f"python3 scripts/check_against_reference.py run convergence-user --solver yoursolver.py:solve "
                   f"--exact {output_file}:exact_solution --order P")
        template = f'''r"""
Method of Manufactured Solutions (MMS) module. Generated by scienceStack mms_generator.py.

Manufactured solution:
    u({signature}) = {latex_exact}
Governing equation:
    L[u] = f({signature}), L[u] = {operator_expr_str}
Forcing term, to add to your solver as a source:
    f({signature}) = {latex_forcing}

Both functions take the coordinates in the order ({signature}).
Measure the order of your solver against exact_solution (P is the order you claim):
    {command}
"""

import math


def exact_solution({signature}):
    return {py_code_u}


def source_term({signature}):
    return {py_code_f}
'''
        with open(output_file, "w") as f:
            f.write(template)
        print(f"--> MMS module written to {output_file}")
        print(f"--> Then run: {command}")


def main():
    parser = argparse.ArgumentParser(description="scienceStack MMS Generator")
    parser.add_argument("--exact", required=True, help="Manufactured solution expression u(x, t)")
    parser.add_argument("--operator", required=True, help="PDE operator expression, e.g. 'diff(u, t) - alpha * diff(u, x, 2)'")
    parser.add_argument("--params", default="", help="Parameter values, e.g. 'alpha=0.1,nu=0.01'")
    parser.add_argument("--output", default="", help="Optional output Python module path")
    parser.add_argument("--vars", default="", help="Coordinates of the generated functions, in order, e.g. 'x,y,t' "
                                                   "(default: those of x, y, z, t the expressions use)")

    args = parser.parse_args()
    generate_mms(args.exact, args.operator, args.params, args.output, args.vars)


if __name__ == "__main__":
    main()

r"""
Method of Manufactured Solutions (MMS) Generator for PDE/ODE Verification.

Uses SymPy to analytically substitute a manufactured exact solution into a
differential operator, deriving the exact analytical source term f(x, t)
and generating a verification test fixture with convergence order O(h^p) assertion.

Usage:
    python3 scripts/mms_generator.py --exact "sin(pi*x) * exp(-t)" \
                                     --operator "diff(u, t) - alpha * diff(u, x, 2)" \
                                     --params "alpha=0.1" \
                                     --output test_mms_heat.py
"""

import sys
import argparse
import sympy as sp


def generate_mms(exact_expr_str: str, operator_expr_str: str, params_str: str = "", output_file: str = ""):
    # Symbols
    t, x, y, z = sp.symbols('t x y z', real=True)
    pi = sp.pi

    # Parse parameter dict
    param_dict = {}
    if params_str:
        for p in params_str.split(","):
            if "=" in p:
                k, v = p.split("=")
                k = k.strip()
                v = float(v.strip())
                param_dict[sp.Symbol(k, real=True)] = v

    # Local evaluation environment
    local_env = {
        't': t, 'x': x, 'y': y, 'z': z,
        'pi': pi, 'sin': sp.sin, 'cos': sp.cos,
        'exp': sp.exp, 'log': sp.log, 'sqrt': sp.sqrt,
    }
    for k in param_dict:
        local_env[str(k)] = k

    # Parse exact manufactured solution u_exact
    u_exact = sp.sympify(exact_expr_str, locals=local_env)

    # Function u(t, x, y, z) for operator evaluation
    # Substitute u with u_exact in operator
    local_env_op = dict(local_env)
    local_env_op['u'] = u_exact
    local_env_op['diff'] = sp.diff

    # Evaluate forcing term f = Operator[u_exact]
    forcing_term = sp.sympify(operator_expr_str, locals=local_env_op)
    forcing_term_simplified = sp.simplify(forcing_term)

    # Substitute numerical parameter values
    forcing_numerical = forcing_term_simplified.subs(param_dict)
    u_exact_numerical = u_exact.subs(param_dict)

    # Generate LaTeX representations
    latex_exact = sp.latex(u_exact)
    latex_forcing = sp.latex(forcing_term_simplified)

    print("=" * 70)
    print("Method of Manufactured Solutions (MMS) Symbolic Derivation:")
    print("=" * 70)
    print(f"Manufactured Solution u_exact(x, t):\n  LaTeX: {latex_exact}\n  SymPy: {u_exact}\n")
    print(f"Differential Operator:\n  L[u] = {operator_expr_str}\n")
    print(f"Exact Analytical Forcing Term f = L[u_exact]:\n  LaTeX: {latex_forcing}\n  SymPy: {forcing_term_simplified}\n")
    if param_dict:
        print(f"Numerical Forcing Term (with params {params_str}):\n  SymPy: {forcing_numerical}\n")
    print("=" * 70)

    # Generate Python code
    py_code_u = sp.pycode(u_exact_numerical)
    py_code_f = sp.pycode(forcing_numerical)

    print("Python Implementations:")
    print(f"def exact_solution(x, t):\n    return {py_code_u}\n")
    print(f"def source_term(x, t):\n    return {py_code_f}\n")

